import type { Metadata, Viewport } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";

const geistSans = Geist({ variable: "--font-geist-sans", subsets: ["latin"] });
const geistMono = Geist_Mono({ variable: "--font-geist-mono", subsets: ["latin"] });

export const metadata: Metadata = {
  title: { default: "muselearning", template: "%s | muselearning" },
  description: "A calmer place to learn: courses, modules, assignments and grades in one quiet interface.",
};

export const viewport: Viewport = {
  themeColor: [
    { media: "(prefers-color-scheme: light)", color: "#f7f7f8" },
    { media: "(prefers-color-scheme: dark)", color: "#0d0e11" },
  ],
};

const themeScript = `var sys=matchMedia("(prefers-color-scheme: dark)").matches;try{var t=localStorage.getItem("muse-theme");document.documentElement.classList.toggle("dark",t?t==="dark":sys)}catch(e){document.documentElement.classList.toggle("dark",sys)}`;

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html lang="en" suppressHydrationWarning className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}>
      <head>
        <script dangerouslySetInnerHTML={{ __html: themeScript }} />
      </head>
      <body className="min-h-full">{children}</body>
    </html>
  );
}
